"""ペナントの日本一の記録（締めたシーズンの優勝球団）。**純粋な値**で、DB にも Django にも触れない。

シーズンを締めるとき、その年のポストシーズンの優勝球団（日本一。1リーグの世界は CS の優勝）を、確定した記録として
保存する（2026-10-24 ユーザー決定。#242）。CLAUDE.md の「同じ事実の出典を2つ作らない」の**例外**で、表彰
（`awards.py`。#248）と同じ扱いにする。範囲は**締めたシーズンの優勝球団だけ**。球団ごとの到達段
（「CS ファイナルステージ敗退」など）・勝ち上がり・順位は保存しない（その年の試合から導く）。

- 書くのはシーズンを締める処理だけで、そのとき勝ち上がり（`postseason.PostseasonBracket`）から導いた優勝球団を
  そのまま写す。締めたシーズンの試合は書き換えないので、保存した優勝球団が後から導いた優勝球団とずれることは無い
- 締めた年を読む画面（歴代の記録・球団史・世界の終了）は記録を読み、終わったが締めていない年
  （`season.unclosed_completed_year`）だけを導く。同じ年を両方から読まない
- 呼び名（「日本一」「CS 優勝」）は持たない。世界のリーグの数で決まる（`postseason.champion_title`）
- ポストシーズンの無い年（方式「なし」・対戦が組めない）は記録を作らない
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Championship:
    """ある年の日本一（ポストシーズンの優勝球団）。世界は球団のリーグで決まる。"""

    year: int
    team_id: int
